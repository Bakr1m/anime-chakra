// Post-build: generate dist/sw.js with a deterministic precache list.
// Reads dist/.vite/manifest.json (build.manifest) so offline reload never
// races the runtime cache: every hashed bundle is cached at install time.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'web', 'dist');
const manifest = JSON.parse(readFileSync(join(root, '.vite', 'manifest.json'), 'utf-8'));

const files = new Set(['./', './index.html', './manifest.webmanifest']);
for (const chunk of Object.values(manifest)) {
  for (const f of [chunk.file, ...(chunk.css ?? [])]) {
    if (f) files.add(`./${f}`);
  }
}
// icons are unhashed static assets
for (const icon of ['icons/icon-192.png', 'icons/icon-512.png', 'icons/maskable-512.png', 'icons/apple-180.png']) {
  files.add(`./${icon}`);
}
// tracking models staged by copy-models.mjs: one visit makes hand/face/seg
// work fully offline (runtime cache-first is only the fallback now)
const modelsDir = join(root, 'models');
if (existsSync(modelsDir)) {
  for (const name of readdirSync(modelsDir)) {
    if (name.endsWith('.task') || name.endsWith('.tflite')) files.add(`./models/${name}`);
  }
}

const sw = `// Generated by scripts/build-sw.mjs - do not edit by hand.
const VERSION = 'chakra-v1';
const PRECACHE = ${JSON.stringify([...files], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(VERSION)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin && !url.hostname.includes('jsdelivr')) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(VERSION).then((c) => c.put('./index.html', copy));
          return res;
        })
        .catch(() => caches.match('./index.html').then((r) => r || fetch(req))),
    );
    return;
  }
  // NOTE: match by URL string against the named cache. Matching the raw
  // Request object missed precached bundles in the wild (header/Vary
  // sensitivity); string matching is proven by the e2e cache probes.
  event.respondWith(
    caches.open(VERSION).then((cache) =>
      cache.match(req.url, { ignoreSearch: true }).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              cache.put(req, copy);
            }
            return res;
          }),
      ),
    ),
  );
});
`;

writeFileSync(join(root, 'sw.js'), sw);
console.log(`sw.js generated with ${files.size} precached assets`);
